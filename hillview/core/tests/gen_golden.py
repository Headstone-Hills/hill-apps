#!/usr/bin/env python3
"""Generate golden.inc: expected outputs from the numpy reference (hillview.effects) for the C++ self-test.

The C++ test rebuilds the same input image with the same LCG, runs the native kernels, and compares.
Run from anywhere:  python3 core/tests/gen_golden.py > core/tests/golden.inc
"""
import os
import sys

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", ".."))
from hillview import effects
from hillview.color import rgb_to_oklab, oklab_to_rgb, parse_color
from hillview.modulation import hash01, source_value

W, H = 37, 23


def lcg_image(w, h, seed=12345):
    s, out = seed, np.empty(w * h * 3, np.uint8)
    for i in range(out.size):
        s = (s * 1664525 + 1013904223) & 0xFFFFFFFF
        out[i] = s >> 24
    out = out.reshape(h, w, 3)
    out[: h // 3, : w // 2] = [200, 30, 40]            # a flat red region so remap rules actually fire
    return out


def to_u8(x):
    return (np.clip(x, 0, 1) * 255 + 0.5).astype(np.uint8)


RULES = [("#c81e28", "#00ffff", 0.20, 0.10, 1.0), ("#808080", "#ff00aa", 0.15, 0.20, 0.7)]
PALETTE = np.array([[0.1, 0.1, 0.1], [0.9, 0.2, 0.2], [0.2, 0.8, 0.3], [0.2, 0.3, 0.9], [0.95, 0.95, 0.9]], np.float32)


def rule_dicts():
    return [{"from": f, "to": t, "threshold": th, "softness": so, "amount": am} for f, t, th, so, am in RULES]


def emit(name, arr):
    flat = ",".join(str(int(v)) for v in np.asarray(arr).reshape(-1))
    print(f"static const uint8_t {name}[] = {{{flat}}};")


img_u8 = lcg_image(W, H)
x = img_u8.astype(np.float32) * np.float32(1 / 255)

print("// Generated by gen_golden.py from the numpy reference. Do not edit.")
print(f"static const int GW = {W}, GH = {H};")
print("static const float G_RULES[][9] = {  // src_lab[3], tgt_rgb[3], threshold, softness, amount")
for f, t, th, so, am in RULES:
    sl, tr = rgb_to_oklab(parse_color(f)), oklab_to_rgb(rgb_to_oklab(parse_color(t)))
    print("  {" + ",".join(f"{float(v):.9e}f" for v in [*sl, *tr, th, so, am]) + "},")
print("};")
print("static const float G_PALETTE[] = {" + ",".join(f"{float(v):.9e}f" for v in PALETTE.reshape(-1)) + "};")

# A: posterize 4 -> smooth 3 -> remap -> blur 2
a = effects.blur(effects.remap_colors(effects.blur(effects.posterize(x, 4), 3.0), rule_dicts()), 2.0)
emit("G_CHAIN_A", to_u8(a))
# B: palette -> blur 1.5 (no remap)
cent = PALETTE
q = np.empty_like(x).reshape(-1, 3)
q[:] = cent[effects._nearest(x.reshape(-1, 3), cent)]
emit("G_CHAIN_B", to_u8(effects.blur(q.reshape(H, W, 3), 1.5)))
# C: remap only
emit("G_REMAP_ONLY", to_u8(effects.remap_colors(x, rule_dicts())))

# modulation
print("static const double G_HASH[][3] = {  // n, seed, value")
for n, s in [(0, 0), (1, 0), (-1, 7), (12345, 3), (2 ** 40, -3), (-7, 2 ** 35)]:
    print(f"  {{{n}.0,{s}.0,{hash01(n, s)!r}}},")
print("};")
print("static const double G_MOD[][8] = {  // type, shape, hz, phase, duty, seed, t, value")
cases = [
    ({"type": "lfo", "shape": "sine", "hz": 0.7, "phase": 0.2}, 0, 0),
    ({"type": "lfo", "shape": "saw", "hz": 1.3}, 0, 1),
    ({"type": "lfo", "shape": "tri", "hz": 2.0, "phase": 0.9}, 0, 2),
    ({"type": "lfo", "shape": "square", "hz": 3.1, "duty": 0.3}, 0, 3),
    ({"type": "noise", "hz": 2.5, "seed": 4}, 1, 0),
    ({"type": "steps", "hz": 5.0, "seed": 9}, 2, 0),
]
for src, typ, shape in cases:
    for t in (-2.37, 0.0, 0.41, 7.89, 33.3):
        print(f"  {{{typ},{shape},{src.get('hz', 1.0)!r},{src.get('phase', 0.0)!r},{src.get('duty', 0.5)!r},"
              f"{src.get('seed', 0)},{t!r},{source_value(src, t)!r}}},")
print("};")
